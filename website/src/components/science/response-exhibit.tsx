"use client";
import { useMemo, useRef, useState } from "react";
import ExhibitFrame from "./exhibit-frame";
import { AxisX, AxisY, INK, SANS, linear } from "@/components/figures/chart-kit";
import { AMPLITUDE_SUPPORT, FAST_MODE_H, HORIZONS, SLOW_MODE_H, innovation, response } from "@/lib/cmj-science.mjs";
import { plotTheme } from "@/lib/plot-theme.mjs";

export default function ResponseExhibit() {
  const svg = useRef<SVGSVGElement>(null);
  const [fast, setFast] = useState(0.04);
  const [slow, setSlow] = useState(0.03);
  const [baseline, setBaseline] = useState(20);
  const taus = useMemo(() => Array.from({ length: 97 }, (_, i) => i), []);
  const W = 640;
  const H = 330;
  const x = linear([0, 96], [70, W - 24]);
  const y = linear([-16, 0.5], [H - 48, 22]);
  const line = (f: (tau: number) => number) => taus.map((tau, i) => `${i ? "L" : "M"}${x(tau)},${y(f(tau) * 100)}`).join(" ");
  const lo = [AMPLITUDE_SUPPORT.fast[0], AMPLITUDE_SUPPORT.slow[0]];
  const hi = [AMPLITUDE_SUPPORT.fast[1], AMPLITUDE_SUPPORT.slow[1]];
  const envelope = `${taus.map((tau, i) => `${i ? "L" : "M"}${x(tau)},${y(response(tau, lo[0], lo[1]) * 100)}`).join(" ")} ${[...taus]
    .reverse()
    .map((tau) => `L${x(tau)},${y(response(tau, hi[0], hi[1]) * 100)}`)
    .join(" ")} Z`;
  const rows = HORIZONS.map((h) => [
    `H${h}`,
    (response(h, fast, slow) * 100).toFixed(2),
    innovation(baseline, h, fast, slow).toFixed(3),
  ]);
  return (
    <ExhibitFrame
      id="exhibit-response"
      chapter="Chapter 2"
      figure={4}
      title="Fixed mathematical response modes of the synthetic generator"
      question="How does the simulator turn a training exposure into a time-dependent change in the measured outcome?"
      svgRef={svg}
      units="Time since exposure h; relative change % of baseline truth; expected innovation N/kg (before measurement noise)."
      readout={
        <p data-testid="response-readout">
          {rows.map((r) => `${r[0]}: ${r[1]} % (${r[2]} N/kg)`).join(" · ")}
        </p>
      }
      interpretation={
        <p>
          After exposure the simulator lowers the outcome by r(τ) = −a<sub>f</sub>·e<sup>−τ/{FAST_MODE_H} h</sup> − a
          <sub>s</sub>·e<sup>−τ/{SLOW_MODE_H} h</sup>. The innovation to be forecast at H24, H48 and H72 is that
          change read at three lags and measured with noise. Amplitudes come from exposure, participant and camp
          effects; here you set them directly.
        </p>
      }
      limitations={[
        "The 24 h and 84 h constants are fixed assumptions of the simulator, not measured recovery time constants.",
        "No biological mechanism, causal claim or athlete data is implied; amplitudes are bounded by the simulator (0.01–0.08 fast, 0–0.08 slow).",
        "The expected innovation omits measurement noise and the bounded model discrepancy.",
      ]}
      table={{
        caption: `Response at the three forecast horizons for a_f = ${fast.toFixed(3)}, a_s = ${slow.toFixed(3)}, baseline ${baseline} N/kg`,
        columns: ["Horizon", "Relative change (%)", "Expected innovation (N/kg)"],
        rows,
      }}
    >
      <p className="pub-status" role="note">
        Synthetic assumption: these curves are generated by the simulator and are not observed recovery.
      </p>
      <div className="sci-controls">
        <label>
          Fast amplitude a<sub>f</sub>: <output>{fast.toFixed(3)}</output>
          <input type="range" min={AMPLITUDE_SUPPORT.fast[0]} max={AMPLITUDE_SUPPORT.fast[1]} step={0.005} value={fast} onChange={(e) => setFast(Number(e.target.value))} aria-label="Fast mode amplitude" />
        </label>
        <label>
          Slow amplitude a<sub>s</sub>: <output>{slow.toFixed(3)}</output>
          <input type="range" min={AMPLITUDE_SUPPORT.slow[0]} max={AMPLITUDE_SUPPORT.slow[1]} step={0.005} value={slow} onChange={(e) => setSlow(Number(e.target.value))} aria-label="Slow mode amplitude" />
        </label>
        <label>
          Baseline force: <output>{baseline} N/kg</output>
          <input type="range" min={16} max={26} step={1} value={baseline} onChange={(e) => setBaseline(Number(e.target.value))} aria-label="Baseline mean force, N/kg" />
        </label>
      </div>
      <svg ref={svg} viewBox={`0 0 ${W} ${H}`} role="img" aria-labelledby="rs-title rs-desc" className="sci-chart">
        <title id="rs-title">Fixed-mode response over 96 hours</title>
        <desc id="rs-desc">
          Relative change in the true outcome versus hours since exposure: fast mode, slow mode and their sum, with the
          amplitude envelope and the three forecast horizons marked.
        </desc>
        <rect width={W} height={H} fill="#fffdf7" />
        <AxisX scale={x} y={H - 48} values={[0, 24, 48, 72, 96]} label="Time since exposure τ (h)" grid={[22, H - 48]} />
        <AxisY scale={y} x={70} values={[-15, -10, -5, 0]} label="Relative change (%)" grid={[70, W - 24]} />
        <path d={envelope} fill={plotTheme.ochre} opacity={0.16} />
        <path d={line((tau) => -fast * Math.exp(-tau / FAST_MODE_H))} fill="none" stroke={plotTheme.ochre} strokeWidth={1.4} strokeDasharray="5 3" />
        <path d={line((tau) => -slow * Math.exp(-tau / SLOW_MODE_H))} fill="none" stroke="#1f7a6d" strokeWidth={1.4} strokeDasharray="5 3" />
        <path d={line((tau) => response(tau, fast, slow))} fill="none" stroke={INK} strokeWidth={2.6} />
        {HORIZONS.map((h) => (
          <g key={h}>
            <line x1={x(h)} x2={x(h)} y1={22} y2={H - 48} stroke={plotTheme.grid} />
            <circle cx={x(h)} cy={y(response(h, fast, slow) * 100)} r={4.5} fill={plotTheme.cobalt} stroke="#fffdf7" strokeWidth={1.5} />
            <text x={x(h)} y={34} textAnchor="middle" fontFamily={SANS} fontSize={12} fontWeight={700} fill={plotTheme.cobalt}>
              H{h}
            </text>
          </g>
        ))}
        <g fontFamily={SANS} fontSize={11.5}>
          <text x={W - 28} y={H - 76} textAnchor="end" fill={plotTheme.ochre}>fast mode (24 h)</text>
          <text x={W - 28} y={H - 92} textAnchor="end" fill="#1f7a6d">slow mode (84 h)</text>
          <text x={W - 28} y={H - 108} textAnchor="end" fill={INK}>sum r(τ)</text>
          <text x={W - 28} y={H - 124} textAnchor="end" fill={plotTheme.muted}>shaded: amplitude support</text>
        </g>
      </svg>
    </ExhibitFrame>
  );
}
